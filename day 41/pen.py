# Pen
import turtle
t = turtle.Turtle()
t.forward(100) # Move the turtle forward by 100 units
t.left(90) # Turn the turtle left by 90 degrees
t.forward(100) # Move the turtle forward by 100 units
t.left(90) # Turn the turtle left by 90 degrees
t.forward(100) # Move the turtle forward by 100 units
t.left(90) # Turn the turtle left by 90 degrees
t.forward(100) # Move the turtle forward by 100 units
# 1 unit is equal to 1 pixel
turtle.done() # Keeps the window open until it is closed by the user